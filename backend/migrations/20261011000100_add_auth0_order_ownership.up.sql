CREATE TABLE auth_principals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT auth_principals_issuer_subject_unique UNIQUE (issuer, subject)
);

ALTER TABLE orders
    ADD COLUMN owner_principal_id BIGINT
    REFERENCES auth_principals(id);

CREATE INDEX orders_owner_status_created_idx
    ON orders (owner_principal_id, status, created_at, id);
